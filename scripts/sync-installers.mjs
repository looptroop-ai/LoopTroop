#!/usr/bin/env node
/**
 * Copies `scripts/installer-core.mjs` into the installer wrappers.
 *
 *   npm run installers:sync     rewrite install.sh and install.ps1
 *   npm run installers:check    fail if either copy has drifted
 *
 * The wrappers have to be standalone single files — `curl … | sh` cannot fetch
 * a second one — so the core exists three times. Generating two of those copies
 * from the third makes drift impossible to introduce by hand, and the `--check`
 * mode makes it impossible to merge.
 */
import { readFileSync, writeFileSync } from 'node:fs'
import { dirname, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const repoRoot = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const CORE_PATH = resolve(repoRoot, 'scripts/installer-core.mjs')
const BEGIN = '# --- BEGIN installer-core (generated by scripts/sync-installers.mjs; do not edit) ---'
const END = '# --- END installer-core ---'
const SH_HEREDOC = 'LOOPTROOP_INSTALLER_CORE'

function fail(message) {
  process.stderr.write(`FAIL: ${message}\n`)
  process.exit(1)
}

const core = readFileSync(CORE_PATH, 'utf8').trimEnd()

// Both embeddings are literal-quoted, so the only thing that can break them is
// the core containing their terminator. Neither is plausible in JavaScript, but
// a silently truncated installer is bad enough to be worth one check.
for (const line of core.split('\n')) {
  if (line === SH_HEREDOC) fail(`installer-core.mjs contains a line equal to the shell heredoc terminator ${SH_HEREDOC}.`)
  if (line.startsWith("'@")) fail("installer-core.mjs contains a line starting with '@, which ends a PowerShell here-string.")
}

/** Replaces everything between the markers, keeping the markers themselves. */
function render(source, path, body) {
  const begin = source.indexOf(BEGIN)
  const end = source.indexOf(END)
  if (begin === -1 || end === -1 || end < begin) fail(`${path} is missing the installer-core markers.`)
  return `${source.slice(0, begin)}${BEGIN}\n${body}\n${source.slice(end)}`
}

const targets = [
  {
    path: resolve(repoRoot, 'install.sh'),
    body: [`cat > "$core" <<'${SH_HEREDOC}'`, core, SH_HEREDOC].join('\n'),
  },
  {
    path: resolve(repoRoot, 'install.ps1'),
    body: ["$core = @'", core, "'@"].join('\n'),
  },
]

const check = process.argv.includes('--check')
const stale = []

for (const target of targets) {
  const current = readFileSync(target.path, 'utf8')
  const next = render(current, target.path, target.body)
  if (current === next) continue
  if (check) stale.push(target.path)
  else writeFileSync(target.path, next)
}

if (check && stale.length > 0) {
  process.stderr.write('\nFAIL: the installer wrappers do not match scripts/installer-core.mjs.\n\n')
  for (const path of stale) process.stderr.write(`  ${path}\n`)
  process.stderr.write('\nRun `npm run installers:sync` and commit the result.\n')
  process.exit(1)
}

process.stdout.write(check
  ? 'PASS: install.sh and install.ps1 match scripts/installer-core.mjs.\n'
  : 'Synced install.sh and install.ps1 from scripts/installer-core.mjs.\n')
