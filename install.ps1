#
#   irm https://www.looptroop.ovh/install.ps1 | iex
#   & ([scriptblock]::Create((irm https://www.looptroop.ovh/install.ps1))) -Version 9.9.9
#   & ([scriptblock]::Create((irm https://www.looptroop.ovh/install.ps1))) -Binary
