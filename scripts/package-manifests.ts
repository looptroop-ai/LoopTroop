/**
 * Renders the descriptor each managed package channel publishes, and reads back
 * the three facts that matter from one somebody else may have written.
 *
 * All three channels install the same bundle, and all three descriptors are
 * therefore the same four values in three syntaxes: version, URL, sha256, and
 * the name of the executable to shim. Rendering them from one place means a
 * release cannot publish a formula and a manifest that disagree about which
 * bytes this version is.
 *
 * Pure, and golden-file tested, because a mistake here is not caught by
 * anything downstream: a formula with a wrong sha256 installs green in CI
 * against the file CI just built and fails for every user.
 */

export type Channel = 'homebrew' | 'scoop' | 'chocolatey'

export interface ChannelInputs {
  version: string
  /** Where the bundle is fetched from. A release asset URL, or a local one in tests. */
  url: string
  sha256: string
}

/**
 * Under 80 characters, not starting with an article or the formula name, as
 * `brew audit --strict` requires. Deliberately not `package.json`'s
 * description, which is three times too long and would fail that check.
 */
export const SHORT_DESCRIPTION = 'Local AI coding orchestration with council planning and human-gated PRs'

export const HOMEPAGE = 'https://www.looptroop.ovh/'
export const REPOSITORY = 'https://github.com/looptroop-ai/LoopTroop'
export const LICENSE = 'MIT'

/** Written at the package root so LoopTroop can name the upgrade command. */
export const CHANNEL_MARKER = '.install-channel'

/** The top-level directory inside the bundle archive. */
export const BUNDLE_ROOT = 'looptroop'

function assertInputs({ version, url, sha256 }: ChannelInputs): void {
  if (!/^\d+\.\d+\.\d+(-[0-9A-Za-z.-]+)?$/.test(version)) throw new Error(`Not a version: ${version}`)
  if (!/^[0-9a-f]{64}$/.test(sha256)) throw new Error(`Not a sha256: ${sha256}`)
  if (url === '') throw new Error('The bundle URL is empty.')
}

/**
 * The Homebrew formula.
 *
 * Two decisions worth naming. `node@24` is keg-only, so its `node` is not on
 * anybody's PATH; the launcher's shebang is `#!/usr/bin/env node`, so a plain
 * symlink into `bin` would install green and then die with `env: node: No such
 * file`. `write_env_script` puts the keg's bin on PATH for this command only.
 *
 * And `uses_from_macos "git"` rather than `depends_on "git"`: macOS provides
 * git, and `brew audit` rejects depending on what the OS already has — but
 * Linuxbrew does not, and `doctor` treats git as required, so it cannot simply
 * be dropped either.
 *
 * There is no `version` field. Homebrew scans one out of the URL — the bundle
 * is named `looptroop-<version>-bundle.tar.gz` — and `brew audit --strict`
 * rejects stating it again. `parseDescriptor` reads it back the same way.
 *
 * The field order is not a matter of taste either: `brew style` enforces it,
 * and rejected `livecheck` after `depends_on` and `Formula["node@24"].opt_bin`
 * in place of `formula_opt_bin`.
 */
export function renderHomebrewFormula(inputs: ChannelInputs): string {
  assertInputs(inputs)

  return `# Generated by scripts/package-manifests.ts. Do not edit by hand.
class Looptroop < Formula
  desc "${SHORT_DESCRIPTION}"
  homepage "${HOMEPAGE}"
  url "${inputs.url}"
  sha256 "${inputs.sha256}"
  license "${LICENSE}"

  livecheck do
    url :stable
    strategy :github_latest
  end

  depends_on "gh"
  depends_on "node@24"
  uses_from_macos "git"

  def install
    libexec.install Dir["*"]
    (libexec/"${CHANNEL_MARKER}").write "homebrew"
    (bin/"looptroop").write_env_script libexec/"bin/looptroop",
                                       PATH: "#{formula_opt_bin("node@24")}:$PATH"
  end

  def caveats
    <<~EOS
      LoopTroop drives OpenCode, which it does not install. Run:
        looptroop doctor
    EOS
  end

  test do
    assert_match version.to_s, shell_output("#{bin}/looptroop --version")
  end
end
`
}

/**
 * The Scoop manifest.
 *
 * `bin` points at the `.cmd` wrapper: Scoop's shim runs the target directly and
 * a `#!` script is not executable on Windows, so shimming `bin/looptroop` would
 * produce a command that exists and cannot run.
 *
 * `checkver` without `autoupdate` on purpose. Autoupdate would make Excavator a
 * second writer of this file, computing its own hash from whatever it found —
 * and the release is supposed to be the only thing that says what a version's
 * bytes are.
 */
export function renderScoopManifest(inputs: ChannelInputs): string {
  assertInputs(inputs)

  const manifest = {
    version: inputs.version,
    description: SHORT_DESCRIPTION,
    homepage: HOMEPAGE,
    license: LICENSE,
    url: inputs.url,
    hash: inputs.sha256,
    extract_dir: BUNDLE_ROOT,
    // `git` because doctor treats it as required, and Windows does not ship it.
    depends: ['nodejs-lts', 'git'],
    bin: [['bin\\looptroop.cmd', 'looptroop']],
    post_install: [
      `Set-Content -LiteralPath "$dir\\${CHANNEL_MARKER}" -Value 'scoop' -NoNewline`,
    ],
    notes: [
      'LoopTroop drives OpenCode, which it does not install. Run: looptroop doctor',
    ],
    checkver: { github: REPOSITORY },
  }

  return `${JSON.stringify(manifest, null, 4)}\n`
}

/**
 * The Chocolatey package specification.
 *
 * The bundle is embedded in the package rather than downloaded at install time,
 * so `LICENSE.txt` and `VERIFICATION.txt` are mandatory: Chocolatey's moderators
 * reject a package carrying binaries whose provenance is not stated.
 */
export function renderNuspec(inputs: ChannelInputs): string {
  assertInputs(inputs)

  return `<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by scripts/package-manifests.ts. Do not edit by hand. -->
<package xmlns="http://schemas.microsoft.com/packaging/2015/06/nuspec.xsd">
  <metadata>
    <id>looptroop</id>
    <version>${inputs.version}</version>
    <packageSourceUrl>${REPOSITORY}</packageSourceUrl>
    <owners>LoopTroop AI</owners>
    <title>LoopTroop</title>
    <authors>LoopTroop AI</authors>
    <projectUrl>${HOMEPAGE}</projectUrl>
    <licenseUrl>${REPOSITORY}/blob/v${inputs.version}/LICENSE</licenseUrl>
    <requireLicenseAcceptance>false</requireLicenseAcceptance>
    <projectSourceUrl>${REPOSITORY}</projectSourceUrl>
    <docsUrl>${HOMEPAGE}docs</docsUrl>
    <bugTrackerUrl>${REPOSITORY}/issues</bugTrackerUrl>
    <tags>looptroop ai coding-agent orchestration opencode cli</tags>
    <summary>${SHORT_DESCRIPTION}</summary>
    <description>${SHORT_DESCRIPTION}. LoopTroop runs as a local background service and drives OpenCode in isolated git worktrees, with human approval gates before anything is delivered.</description>
    <dependencies>
      <dependency id="nodejs-lts" version="24.15.0" />
      <dependency id="git" />
    </dependencies>
  </metadata>
  <files>
    <file src="tools\\**" target="tools" />
  </files>
</package>
`
}

/** The bundle's file name for a version, which several of these have to agree on. */
export function bundleFileName(version: string): string {
  return `looptroop-${version}-bundle.tar.gz`
}

/**
 * The same bundle as a ZIP, which is the only archive format WinGet reads.
 *
 * `InstallerType: zip` means ZIP; there is no tar.gz option, so this is a
 * second asset rather than a preference.
 */
export function bundleZipFileName(version: string): string {
  return `looptroop-${version}-bundle.zip`
}

/** The standalone Windows binary's archive, which is what WinGet installs. */
export function windowsBinaryZipName(version: string): string {
  return `looptroop-${version}-win-x64.zip`
}

/**
 * Publisher and package, joined, as WinGet identifies a package everywhere.
 *
 * `winget-pkgs` derives the directory from this, so it is not a free choice
 * once published: renaming it later means a new package and an orphaned old one.
 */
export const WINGET_IDENTIFIER = 'LoopTroopAI.LoopTroop'

/** WinGet manifests are versioned by schema; every file must state the same one. */
export const WINGET_MANIFEST_VERSION = '1.6.0'

/**
 * Where these three files go inside a `winget-pkgs` checkout.
 *
 * The convention is `manifests/<first letter, lowercased>/<Publisher>/<Package>/<Version>/`,
 * and the validation pipeline rejects anything else.
 */
export function wingetManifestDir(version: string): string {
  const [publisher, name] = WINGET_IDENTIFIER.split('.')
  return `manifests/${publisher![0]!.toLowerCase()}/${publisher}/${name}/${version}`
}

/**
 * The three YAML files WinGet requires per version.
 *
 * Three files rather than one because WinGet separates what a version *is*
 * (`version`), how it installs (`installer`) and how it reads to a human
 * (`defaultLocale`). They are returned together, keyed by file name, because
 * publishing fewer than all three is never valid.
 *
 * Two decisions worth naming.
 *
 * It installs the **standalone binary**, not the bundle every other channel
 * takes. That is not a preference: `winget validate` refuses a portable whose
 * `RelativeFilePath` is anything but an `.exe`, and rejected the bundle's
 * `.cmd` shim outright —
 *
 *   Manifest Error: The file type of the referenced file is not allowed.
 *   [RelativeFilePath] Value: looptroop\\bin\\looptroop.cmd
 *
 * The winget *client* does run `.cmd` portables; the repository's validation
 * pipeline does not accept them. `PortableCommandAlias` is what puts
 * `looptroop` on the user's PATH.
 *
 * And it declares only git. The binary carries its own Node runtime, so
 * unlike the Homebrew, Scoop and Chocolatey packages there is nothing to
 * install for it — but `doctor` still treats git as required and Windows does
 * not ship one.
 *
 * `Architecture: x64`, not `neutral`. The field describes the *installed
 * binary*, not the archive that carries it, and this archive carries an x64
 * executable and nothing else. `neutral` means the payload runs on any
 * architecture, which would offer this package on Windows on ARM — a target
 * `build-binary.mjs` deliberately does not build and `binaryTarget` refuses by
 * name.
 */
export function renderWingetManifests(inputs: ChannelInputs): Record<string, string> {
  assertInputs(inputs)

  const header = `# Generated by scripts/package-manifests.ts. Do not edit by hand.
PackageIdentifier: ${WINGET_IDENTIFIER}
PackageVersion: ${inputs.version}
`

  return {
    [`${WINGET_IDENTIFIER}.yaml`]: `${header}DefaultLocale: en-US
ManifestType: version
ManifestVersion: ${WINGET_MANIFEST_VERSION}
`,

    [`${WINGET_IDENTIFIER}.installer.yaml`]: `${header}MinimumOSVersion: 10.0.17763.0
InstallerType: zip
NestedInstallerType: portable
NestedInstallerFiles:
  - RelativeFilePath: looptroop-${inputs.version}-win-x64\\looptroop.exe
    PortableCommandAlias: looptroop
Dependencies:
  PackageDependencies:
    - PackageIdentifier: Git.Git
Installers:
  - Architecture: x64
    InstallerUrl: ${inputs.url}
    InstallerSha256: ${inputs.sha256.toUpperCase()}
ManifestType: installer
ManifestVersion: ${WINGET_MANIFEST_VERSION}
`,

    [`${WINGET_IDENTIFIER}.locale.en-US.yaml`]: `${header}PackageLocale: en-US
Publisher: LoopTroop AI
PublisherUrl: ${HOMEPAGE}
PackageName: LoopTroop
PackageUrl: ${REPOSITORY}
License: ${LICENSE}
LicenseUrl: ${REPOSITORY}/blob/v${inputs.version}/LICENSE
ShortDescription: ${SHORT_DESCRIPTION}
Description: ${SHORT_DESCRIPTION}. LoopTroop runs as a local background service and drives OpenCode in isolated git worktrees, with human approval gates before anything is delivered.
Tags:
  - ai
  - cli
  - coding-agent
  - opencode
  - orchestration
ManifestType: defaultLocale
ManifestVersion: ${WINGET_MANIFEST_VERSION}
`,
  }
}

/**
 * Chocolatey's install script.
 *
 * The archive travels inside the package, so this extracts rather than
 * downloads. Two passes through `Get-ChocolateyUnzip` because that is how it
 * handles a `.tar.gz` — the first unwraps the gzip to a `.tar`, the second
 * unpacks it — and because using Chocolatey's own helpers rather than shelling
 * out to `tar.exe` is what its moderators expect to see.
 *
 * `Install-BinFile` shims `looptroop.cmd`, never the POSIX wrapper: a `#!`
 * script is not executable on Windows, so shimming it would create a command
 * that exists and cannot run.
 */
/**
 * What the AUR calls this package.
 *
 * `-bin` because Arch's convention is that a bare name builds from source and
 * a `-bin` suffix installs prebuilt artefacts, and this installs the bundle a
 * release already built. Calling it `looptroop` would promise a from-source
 * build that this `PKGBUILD` does not do.
 */
export const AUR_PACKAGE_NAME = 'looptroop-bin'

/**
 * The AUR package: a `PKGBUILD` and the `.SRCINFO` that must accompany it.
 *
 * The bundle rather than the standalone executable, which is the opposite of
 * the choice WinGet forced. Arch ships a current `nodejs` in its own
 * repositories, so depending on it costs a user one already-installed package
 * and saves them 160 MB of a second Node — the bloat that makes a `-bin`
 * package unwelcome on a distribution built around shared system libraries.
 *
 * `arch=('any')` is not a shortcut. The bundle is verified at build time to
 * contain no compiled code and no platform-specific packages — that is what
 * `verify-no-native-addons.mjs` is for — so one package genuinely serves
 * x86_64 and aarch64, and claiming otherwise would mean publishing two
 * identical packages.
 *
 * `.SRCINFO` is rendered here rather than only being generated, so that CI can
 * diff this against what `makepkg --printsrcinfo` actually produces. The AUR
 * rejects a push whose `.SRCINFO` disagrees with its `PKGBUILD`, and that
 * rejection would otherwise arrive during a release.
 */
export function renderAurPackage(inputs: ChannelInputs): Record<string, string> {
  assertInputs(inputs)

  const fields = {
    pkgdesc: SHORT_DESCRIPTION,
    url: HOMEPAGE,
    // `nodejs>=24`: the floor the application declares. Arch has no `node@24`
    // to pin to, and does not want one — a rolling distribution expects the
    // current runtime, which is why this is a floor rather than an equality.
    depends: ['nodejs>=24', 'git'],
    // `doctor` reports gh as optional and runs without it, so a hard dependency
    // would overstate what LoopTroop needs.
    optdepends: ['github-cli: create and review pull requests from LoopTroop'],
    provides: ['looptroop'],
    conflicts: ['looptroop'],
  }

  const source = `looptroop-${inputs.version}.tar.gz::${inputs.url}`

  const pkgbuild = `# Generated by scripts/package-manifests.ts. Do not edit by hand.
# Maintainer: LoopTroop <noreply@looptroop.ovh>
pkgname=${AUR_PACKAGE_NAME}
pkgver=${inputs.version}
pkgrel=1
pkgdesc="${fields.pkgdesc}"
arch=('any')
url="${fields.url}"
license=('${LICENSE}')
depends=(${fields.depends.map((value) => `'${value}'`).join(' ')})
optdepends=(${fields.optdepends.map((value) => `'${value}'`).join(' ')})
provides=(${fields.provides.map((value) => `'${value}'`).join(' ')})
conflicts=(${fields.conflicts.map((value) => `'${value}'`).join(' ')})
source=("${source}")
sha256sums=('${inputs.sha256}')

package() {
  install -d "\${pkgdir}/usr/lib/${AUR_PACKAGE_NAME}"
  cp -a "\${srcdir}/${BUNDLE_ROOT}/." "\${pkgdir}/usr/lib/${AUR_PACKAGE_NAME}/"

  # The bundle is one archive for four channels, so it carries the Windows
  # wrappers too. They cannot run here, and \`namcap\` reads the \`.ps1\` shebang
  # and asks for a pwsh dependency to satisfy them.
  rm -f "\${pkgdir}/usr/lib/${AUR_PACKAGE_NAME}/bin/looptroop.cmd" \\
    "\${pkgdir}/usr/lib/${AUR_PACKAGE_NAME}/bin/looptroop.ps1"

  # Says which channel installed this, so \`looptroop doctor\` names the right
  # upgrade command rather than inferring one from a path that several
  # channels could have produced.
  printf 'aur' > "\${pkgdir}/usr/lib/${AUR_PACKAGE_NAME}/${CHANNEL_MARKER}"

  # A symlink, which the launcher resolves before working out where its own
  # \`dist\` lives — that is what the readlink loop in the wrapper is for.
  install -d "\${pkgdir}/usr/bin"
  ln -s "/usr/lib/${AUR_PACKAGE_NAME}/bin/looptroop" "\${pkgdir}/usr/bin/looptroop"

  install -Dm644 "\${srcdir}/${BUNDLE_ROOT}/LICENSE" \\
    "\${pkgdir}/usr/share/licenses/\${pkgname}/LICENSE"
}
`

  // The field order is makepkg's, not ours: `--printsrcinfo` emits pkgbase,
  // then the metadata fields in declaration order, then the sources. A diff
  // against this file is only meaningful if it is byte-comparable.
  const srcinfo = `pkgbase = ${AUR_PACKAGE_NAME}
\tpkgdesc = ${fields.pkgdesc}
\tpkgver = ${inputs.version}
\tpkgrel = 1
\turl = ${fields.url}
\tarch = any
\tlicense = ${LICENSE}
${fields.depends.map((value) => `\tdepends = ${value}\n`).join('')}${fields.optdepends.map((value) => `\toptdepends = ${value}\n`).join('')}${fields.provides.map((value) => `\tprovides = ${value}\n`).join('')}${fields.conflicts.map((value) => `\tconflicts = ${value}\n`).join('')}\tsource = ${source}
\tsha256sums = ${inputs.sha256}

pkgname = ${AUR_PACKAGE_NAME}
`

  return { PKGBUILD: pkgbuild, '.SRCINFO': srcinfo }
}

export function renderChocolateyInstall(version: string): string {
  return `# Generated by scripts/package-manifests.ts. Do not edit by hand.
$ErrorActionPreference = 'Stop'

$toolsDir = Split-Path -Parent $MyInvocation.MyCommand.Definition
$archive = Join-Path $toolsDir '${bundleFileName(version)}'
$appDir = Join-Path $toolsDir 'app'

Get-ChocolateyUnzip -FileFullPath $archive -Destination $toolsDir
$tarball = Get-ChildItem -LiteralPath $toolsDir -Filter '*.tar' | Select-Object -First 1
if (-not $tarball) { throw 'The embedded archive did not contain a tar file.' }

Get-ChocolateyUnzip -FileFullPath $tarball.FullName -Destination $appDir
Remove-Item -LiteralPath $tarball.FullName -Force

$packageRoot = Join-Path $appDir '${BUNDLE_ROOT}'
if (-not (Test-Path -LiteralPath (Join-Path $packageRoot 'package.json'))) {
  throw "The archive did not unpack to $packageRoot."
}

# So \`looptroop doctor\` names \`choco upgrade looptroop\` and not some other
# manager's command.
Set-Content -LiteralPath (Join-Path $packageRoot '${CHANNEL_MARKER}') -Value 'chocolatey' -NoNewline

Install-BinFile -Name 'looptroop' -Path (Join-Path $packageRoot 'bin\\looptroop.cmd')
`
}

export function renderChocolateyUninstall(): string {
  return `# Generated by scripts/package-manifests.ts. Do not edit by hand.
$ErrorActionPreference = 'Stop'

$toolsDir = Split-Path -Parent $MyInvocation.MyCommand.Definition
$shimTarget = Join-Path $toolsDir 'app\\${BUNDLE_ROOT}\\bin\\looptroop.cmd'

# Named explicitly rather than left to the package directory being deleted: an
# orphaned shim keeps answering \`looptroop\` with a path that no longer exists.
Uninstall-BinFile -Name 'looptroop' -Path $shimTarget
`
}

