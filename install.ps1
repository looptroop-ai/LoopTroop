 */
function nodeHelp(platform) {
  if (platform === 'darwin') return 'brew install node   (or download from https://nodejs.org/)'
  if (platform === 'win32') return 'winget install OpenJS.NodeJS.LTS   (or download from https://nodejs.org/)'
