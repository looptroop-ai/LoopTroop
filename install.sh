#!/bin/sh
# LoopTroop installer for macOS and Linux.
#
#   curl --proto '=https' --proto-redir '=https' --tlsv1.2 -fsSL https://www.looptroop.ovh/install | sh
#   curl --proto '=https' --proto-redir '=https' --tlsv1.2 -fsSL https://www.looptroop.ovh/install | sh -s -- --version 9.9.9
#   curl --proto '=https' --proto-redir '=https' --tlsv1.2 -fsSL https://www.looptroop.ovh/install | sh -s -- --binary
#
# Downloads what a LoopTroop release published, checks it against the checksum
# that release recorded, and installs it: the npm package with npm by default,
# or with `--binary` the standalone executable into ~/.looptroop. It never
# installs Node and never asks for sudo.
#
# All of the actual work is in `scripts/installer-core.mjs`, copied verbatim
# into the block at the bottom of this file. Node is required to install
# LoopTroop at all, so doing the JSON, HTTPS, semver and hashing there rather
# than here means one implementation instead of one per shell, and no dependency
# on curl, jq or shasum being present and identical on every platform.
set -eu

node_missing() {
# --- BEGIN node-floor (generated by scripts/sync-installers.mjs; do not edit) ---
  echo "LoopTroop needs Node.js 24.18.1 or newer and it is not on your PATH." >&2
  echo "" >&2
  case "$(uname -s 2>/dev/null || echo unknown)" in
    Darwin) echo "  brew install node" >&2 ;;
    Linux)  echo "  Use your distribution's package or https://github.com/nvm-sh/nvm" >&2 ;;
    *)      echo "  https://nodejs.org/" >&2 ;;
  esac
# --- END node-floor ---
  echo "  ...or download an installer from https://nodejs.org/" >&2
  echo "" >&2
  echo "Then run this installer again. It will not install Node for you." >&2
  # Including for `--binary`, which surprises people: the standalone executable
  # carries its own Node, but this installer is itself a Node program, so it
  # still needs one to run. Anybody with none at all wants the archive.
  for arg in "$@"; do
    if [ "$arg" = "--binary" ]; then
      echo "" >&2
      echo "That applies to --binary too: this installer is itself a Node program." >&2
      echo "With no Node at all, download and unpack the archive yourself:" >&2
      echo "  https://github.com/looptroop-ai/LoopTroop/releases/latest" >&2
      break
    fi
  done
  exit 1
}

# `node` is looked up on PATH by this shell, twice below, before the core and
# its resolver run — and an empty or relative PATH entry is the current
# directory. A trailing colon, the everyday result of `PATH=$PATH:`, or a `.`,
# and `curl … | sh` run from a Downloads folder would run a `node` sitting in it.
# The core's resolver never searches there; this is the same rule for the
# lookups made before it exists. Everything started from here inherits the
# cleaned PATH. Globbing is off while PATH is split, so an entry holding `*`
# stays one entry.
absolute_path=
saved_ifs=$IFS
IFS=:
set -f
for entry in ${PATH:-}; do
  case "$entry" in
    /*) absolute_path="${absolute_path:+$absolute_path:}$entry" ;;
  esac
done
set +f
IFS=$saved_ifs
# Nothing absolute left means no directory `node` could be in — and an empty
# PATH is the current directory to the shell, the one place this block exists to
# rule out. So it is `node` missing, reported with the system directories as the
# PATH for the one command that report runs.
if [ -z "$absolute_path" ]; then
  PATH=/usr/bin:/bin
  export PATH
  node_missing "$@"
fi
PATH=$absolute_path
export PATH

command -v node >/dev/null 2>&1 || node_missing "$@"

work=$(mktemp -d 2>/dev/null || mktemp -d -t looptroop-install)
# `sh` has no scoped cleanup, and leaving the core behind in a world-readable
# temp directory is untidy rather than dangerous, but it is still litter.
#
# On EXIT, so that it also runs for a signal handled below: those handlers end
# in `exit`, and `exit` runs this. HUP is here because a terminal closing mid
# install is one of the ways this script stops.
trap 'rm -rf "$work"' EXIT INT TERM HUP
core="$work/installer-core.mjs"

# --- BEGIN installer-core (generated by scripts/sync-installers.mjs; do not edit) ---
cat > "$core" <<'LOOPTROOP_INSTALLER_CORE'
#!/usr/bin/env node
/**
 * Installs LoopTroop from a GitHub release, verifying the bytes first.
 *
 *   node installer-core.mjs [--version X.Y.Z] [--tarball PATH] [--dry-run]
 *   node installer-core.mjs --binary [--prefix DIR]
 *
 * This is the whole installer. `install.sh` and `install.ps1` are wrappers that
 * find Node, write this file to a temporary directory and run it — everything
 * that could get a decision wrong lives here, once, where it can be tested,
 * rather than twice in two shell dialects. `scripts/sync-installers.mjs`
 * copies this file into both wrappers and CI fails if a copy has drifted.
 *
 * Node is a hard prerequisite either way, so using it for JSON, semver, HTTPS
 * and hashing costs nothing and avoids depending on curl, jq, shasum or
 * certutil being present and behaving the same on three platforms.
 *
 * By default it installs an npm tarball, with npm (D2a): `npm uninstall -g
 * looptroop` and `npm install -g looptroop@latest` keep working afterwards,
 * which would not be true of an installer that unpacked files itself.
 *
 * `--binary` installs the standalone executable instead — one file carrying its
 * own Node — into a directory this installer owns. That mode unpacks files
 * itself, so it has to do by hand everything npm was doing for us: see
 * `installBinary` for why each step is there.
 *
 * Note that `--binary` still needs Node *to install*, because these wrappers are
 * Node programs. What it removes is Node as a requirement to **run** LoopTroop
 * afterwards. Somebody with no Node at all downloads the archive from the
 * releases page and unpacks it; there is nothing this script can do for them.
 */
import { spawnSync } from 'node:child_process'
import { createHash, randomUUID } from 'node:crypto'
import {
  chmodSync, closeSync, copyFileSync, existsSync, mkdirSync, mkdtempSync, openSync, readFileSync,
  readSync, readdirSync, realpathSync, renameSync, rmSync, statSync, writeFileSync, writeSync,
} from 'node:fs'
import { homedir, tmpdir } from 'node:os'
import { basename, delimiter, dirname, join, resolve } from 'node:path'
