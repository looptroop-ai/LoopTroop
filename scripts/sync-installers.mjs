#!/usr/bin/env node
/**
 * Writes the copies of things this repository states once.
 *
 *   npm run installers:sync     rewrite the generated blocks
 *   npm run installers:check    fail if any copy has drifted
 *
 * Two sources, three destination files, five generated blocks:
 *
 * - `scripts/installer-core.mjs` is copied into `install.sh` and `install.ps1`.
 *   The wrappers have to be standalone single files — `curl … | sh` cannot fetch
 *   a second one — so the core exists three times. Generating two of those
 *   copies from the third makes drift impossible to introduce by hand, and the
 *   `--check` mode makes it impossible to merge.
 *
 * - `server/lib/executablePath.ts` is copied into `scripts/installer-core.mjs`,
 *   with its TypeScript types stripped. The core cannot import it -- it runs
 *   from a temporary file with no repository around it -- and the hand-written
 *   second copy that used to answer that question is what drifted: it searched
 *   `PATH` only and ignored the operator override, so the daemon and the
 *   installer could resolve different binaries on the same machine.
 *
 * - `package.json`'s `engines.node` is the Node floor, and it is stated again in
 *   the two wrappers' prerequisite lines and in `server/cli/launcher.cjs`. None
 *   of those three can import it: two are shell, and the launcher must stay ES5
 *   CommonJS with no dependencies so that an old Node parses it and prints a
 *   message rather than a SyntaxError. They said `24 LTS`, `24 LTS` and
 *   `24.18.0` against an `engines` of `>=24.18.1`.
 */
import { spawnSync } from 'node:child_process'
import { mkdtempSync, readFileSync, rmSync, writeFileSync } from 'node:fs'
import { tmpdir } from 'node:os'
import { stripTypeScriptTypes } from 'node:module'
import { dirname, join, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

// `stripTypeScriptTypes` is still flagged experimental, and Node writes that
// notice to stderr on import. Left alone it prints on every `installers:check`
// run, including the green ones, which is how a real warning stops being read.
// Node's own printer is a listener like any other, so it has to go before a
// filtered one can take its place.
process.removeAllListeners('warning')
process.on('warning', (warning) => {
  if (warning.name === 'ExperimentalWarning' && warning.message.includes('stripTypeScriptTypes')) return
  process.stderr.write(`${warning.name}: ${warning.message}\n`)
})

const repoRoot = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const CORE_PATH = resolve(repoRoot, 'scripts/installer-core.mjs')
const RESOLVER_PATH = resolve(repoRoot, 'server/lib/executablePath.ts')
const BEGIN = '# --- BEGIN installer-core (generated by scripts/sync-installers.mjs; do not edit) ---'
const END = '# --- END installer-core ---'
const FLOOR_BEGIN = '# --- BEGIN node-floor (generated by scripts/sync-installers.mjs; do not edit) ---'
const FLOOR_END = '# --- END node-floor ---'
const SH_HEREDOC = 'LOOPTROOP_INSTALLER_CORE'

function fail(message, ...detail) {
  process.stderr.write(`FAIL: ${message}\n`)
  // The second line of every refusal here is the part that says what to do.
  // It was passed and silently dropped for as long as this took one parameter.
  for (const line of detail) process.stderr.write(`  ${line}\n`)
  process.exit(1)
}

const RESOLVER_BEGIN = '// --- BEGIN executable-path (generated by scripts/sync-installers.mjs; do not edit) ---'
const RESOLVER_END = '// --- END executable-path ---'

const engines = JSON.parse(readFileSync(resolve(repoRoot, 'package.json'), 'utf8')).engines.node
// The same grammar `parseNodeFloor` enforces in `shared/nodeFloor.ts`, repeated
// here because this script is `.mjs` and cannot import the TypeScript module.
// Reading the floor component by component is what made `>=24.bad.1` mean
// `24.0.1` — not a lenient floor but a floor every runtime clears, generated
// into every channel at once, with each copy agreeing with the others.
const floorMatch = /^\s*(?:>=\s*)?v?(\d+)\.(\d+)\.(\d+)\s*$/.exec(String(engines))
if (!floorMatch) fail(`package.json engines.node is unreadable as a floor: ${JSON.stringify(engines)}. Expected a form like ">=24.18.1".`)
const major = Number(floorMatch[1])
const minor = Number(floorMatch[2])
const patch = Number(floorMatch[3])
if (major <= 0) fail(`package.json engines.node is unreadable as a floor: ${JSON.stringify(engines)}. Expected a form like ">=24.18.1".`)
const floorLabel = `${major}.${minor}.${patch}`

/** Replaces everything between a pair of markers, keeping the markers themselves. */
function render(source, path, begin, end, body) {
  const from = source.indexOf(begin)
  const to = source.indexOf(end)
  const name = /BEGIN ([a-z-]+)/.exec(begin)?.[1] ?? 'generated'
  if (from === -1 || to === -1 || to < from) fail(`${path} is missing the ${name} markers.`)
  return `${source.slice(0, from)}${begin}\n${body}\n${source.slice(to)}`
}

/**
 * Top-level names a module source binds, so a collision can be refused here
 * rather than discovered as a SyntaxError inside a downloaded installer.
 *
 * Deliberately shallow: it reads the two forms the generated block actually
 * uses -- `import * as x from`, and a top-level `const`/`function`, exported or
 * not -- rather than parsing JavaScript. A form it cannot see is a form the
 * resolver must not start using.
 */
function topLevelNames(source) {
  const names = new Set()
  for (const line of source.split('\n')) {
    const star = /^import \* as ([A-Za-z_$][\w$]*) from /.exec(line)
    if (star) names.add(star[1])
    const declared = /^(?:export )?(?:async )?(?:function|const|let|var|class) ([A-Za-z_$][\w$]*)/.exec(line)
    if (declared) names.add(declared[1])
  }
  return names
}

/**
 * The resolver as JavaScript.
 *
 * Node's own type stripping, so the copy cannot disagree with what
 * `node server/lib/executablePath.ts` runs. `mode: 'strip'` blanks the
 * annotations in place rather than rewriting anything, which keeps the copy
 * comparable with its source line for line and refuses the TypeScript that
 * would need real transformation -- `enum`, `namespace`, parameter properties --
 * which is exactly the constraint that file is written under.
 */
const resolverBody = stripTypeScriptTypes(readFileSync(RESOLVER_PATH, 'utf8'), { mode: 'strip' })
  // Blanking an annotation in place leaves the spaces it occupied at the end of
  // the line — `let resolved: string` becomes `let resolved` and eight spaces.
  // Trimmed per line, so the three generated copies stay diff-clean; nothing
  // else about the lines moves.
  .split('\n')
  .map((line) => line.trimEnd())
  .join('\n')
  .trimEnd()

const coreSource = readFileSync(CORE_PATH, 'utf8')
const resolverFrom = coreSource.indexOf(RESOLVER_BEGIN)
const resolverTo = coreSource.indexOf(RESOLVER_END)
if (resolverFrom === -1 || resolverTo === -1) fail(`${CORE_PATH} is missing the executable-path markers.`)
const coreWithoutResolver = coreSource.slice(0, resolverFrom) + coreSource.slice(resolverTo)
const coreNames = topLevelNames(coreWithoutResolver)
for (const name of topLevelNames(resolverBody)) {
  if (coreNames.has(name)) {
    fail(
      `scripts/installer-core.mjs already declares '${name}' at the top level, and the generated resolver binds it too.`,
      'Rename one of them: two top-level bindings of the same name is a SyntaxError in a file nobody runs until an install.',
    )
  }
}

const coreNext = render(coreSource, CORE_PATH, RESOLVER_BEGIN, RESOLVER_END, resolverBody)
const core = coreNext.trimEnd()

// The name check above reads two declaration forms and nothing else, so it is a
// friendly early message rather than the guarantee. The guarantee is Node
// parsing what will actually ship: a duplicate binding, or a form the stripper
// let through, is an early SyntaxError that `--check` reports without running a
// line of the installer.
{
  const scratch = mkdtempSync(join(tmpdir(), 'looptroop-installer-core-'))
  try {
    const assembled = join(scratch, 'installer-core.mjs')
    writeFileSync(assembled, `${core}\n`)
    const parsed = spawnSync(process.execPath, ['--check', assembled], { encoding: 'utf8' })
    if (parsed.status !== 0) {
      fail('The assembled installer core does not parse.', ...String(parsed.stderr || parsed.error || '').trim().split('\n'))
    }
  } finally {
    rmSync(scratch, { recursive: true, force: true })
  }
}

// Both embeddings are literal-quoted, so the only thing that can break them is
// the core containing their terminator. Neither is plausible in JavaScript, but
// a silently truncated installer is bad enough to be worth one check.
for (const line of core.split('\n')) {
  if (line === SH_HEREDOC) fail(`installer-core.mjs contains a line equal to the shell heredoc terminator ${SH_HEREDOC}.`)
  if (line.startsWith("'@")) fail("installer-core.mjs contains a line starting with '@, which ends a PowerShell here-string.")
}

const targets = [
  // First, so the wrappers below embed a core whose own generated block is
  // already current. The other way round, `installers:check` would pass while
  // the copy inside the core was stale.
  { path: CORE_PATH, content: coreNext },
  {
    path: resolve(repoRoot, 'install.sh'),
    blocks: [
      {
        begin: BEGIN,
        end: END,
        body: [`cat > "$core" <<'${SH_HEREDOC}'`, core, SH_HEREDOC].join('\n'),
      },
      {
        begin: FLOOR_BEGIN,
        end: FLOOR_END,
        // A whole, closed `case`. It used to open here and close outside the
        // markers, with the Linux and fallback arms handwritten below — so any
        // change to this body that did not happen to end mid-`case` would have
        // left `install.sh` unparseable, and only at the moment somebody piped
        // it into `sh`.
        body: [
          `  echo "LoopTroop needs Node.js ${floorLabel} or newer and it is not on your PATH." >&2`,
          '  echo "" >&2',
          '  case "$(uname -s 2>/dev/null || echo unknown)" in',
          // The unversioned formula, because `node@24` is keg-only: Homebrew
          // installs it and deliberately leaves it off PATH, so the versioned
          // command answers this message with the same message.
          `    Darwin) echo "  brew install node" >&2 ;;`,
          '    Linux)  echo "  Use your distribution\'s package or https://github.com/nvm-sh/nvm" >&2 ;;',
          '    *)      echo "  https://nodejs.org/" >&2 ;;',
          '  esac',
        ].join('\n'),
      },
    ],
  },
  {
    path: resolve(repoRoot, 'install.ps1'),
    blocks: [
      {
        begin: BEGIN,
        end: END,
        body: ["$core = @'", core, "'@"].join('\n'),
      },
      {
        begin: FLOOR_BEGIN,
        end: FLOOR_END,
        // The install line belongs in here too. Left handwritten below the
        // markers it was the one piece of platform help no drift check read.
        body: [
          `  Write-Host 'LoopTroop needs Node.js ${floorLabel} or newer and it is not on your PATH.' -ForegroundColor Red`,
          "  Write-Host ''",
          "  Write-Host '  winget install OpenJS.NodeJS.LTS'",
        ].join('\n'),
      },
    ],
  },
  {
    path: resolve(repoRoot, 'server/cli/launcher.cjs'),
    blocks: [
      {
        // The launcher is JavaScript, but `#` opens no comment there, so its
        // markers are the shell form written as `//` lines instead.
        begin: `//${FLOOR_BEGIN.slice(1)}`,
        end: `//${FLOOR_END.slice(1)}`,
        body: [
          `var REQUIRED_MAJOR = ${major}`,
          `var REQUIRED_MINOR = ${minor}`,
          `var REQUIRED_PATCH = ${patch}`,
        ].join('\n'),
      },
    ],
  },
]

const check = process.argv.includes('--check')
const stale = []

for (const target of targets) {
  const current = readFileSync(target.path, 'utf8')
  let next = target.content ?? current
  for (const block of target.blocks ?? []) {
    next = render(next, target.path, block.begin, block.end, block.body)
  }
  if (current === next) continue
  if (check) stale.push(target.path)
  else writeFileSync(target.path, next)
}

if (check && stale.length > 0) {
  process.stderr.write('\nFAIL: generated blocks are out of date with server/lib/executablePath.ts, scripts/installer-core.mjs or engines.node.\n\n')
  for (const path of stale) process.stderr.write(`  ${path}\n`)
  process.stderr.write('\nRun `npm run installers:sync` and commit the result.\n')
  process.exit(1)
}

process.stdout.write(check
  ? 'PASS: installer-core.mjs, install.sh, install.ps1 and launcher.cjs match executablePath.ts and engines.node.\n'
  : 'Synced installer-core.mjs, install.sh, install.ps1 and launcher.cjs from executablePath.ts and engines.node.\n')
